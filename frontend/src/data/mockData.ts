function generateInitialCertificates(batches: Batch[]): Certificate[] {
  const issuedBatches = batches.filter((b) => b.status === 'Issued');
  const certs: Certificate[] = [];

  issuedBatches.forEach((batch) => {
    batch.candidates.forEach((cand, idx) => {
      const certNum = `PSM-CERT-2026-${batch.id.replace('batch-', '')}${String(idx + 1).padStart(3, '0')}`;
      const isCancelled = certNum === 'PSM-CERT-2026-101004' || certNum === 'PSM-CERT-2026-109007';

      let whatsappStatus: Certificate['whatsappStatus'] = 'Delivered';
      let whatsappFailureReason: string | undefined;

      if (isCancelled) {
        whatsappStatus = 'Delivered';
      } else if (idx % 9 === 5) {
        whatsappStatus = 'Failed';
        whatsappFailureReason = 'Recipient WhatsApp account unreachable (Opt-out or inactive number).';
      } else if (idx % 7 === 3) {
        whatsappStatus = 'Sent';
      } else if (idx % 11 === 8) {
        whatsappStatus = 'Pending';
      }

      certs.push({
        id: `cert-${batch.id}-${idx + 1}`,
        certificateNumber: certNum,
        batchId: batch.id,
        batchNumber: batch.batchNumber,
        candidateId: cand.id,
        candidateName: cand.fullName,
        candidateRegNo: cand.registrationNumber,
        courseName: batch.courseName,
        courseCode: batch.courseCode,
        sector: batch.sector,
        trainingCentre: batch.trainingCentre,
        district: batch.district,
        issueDate: batch.lastUpdated.slice(0, 10),
        status: isCancelled ? 'Cancelled' : 'Issued',
        cancellationReason: isCancelled
          ? 'Duplicate enrolment detected across two state skilling schemes during post-issuance audit.'
          : undefined,
        cancelledBy: isCancelled ? 'Farah Siddiqui' : undefined,
        cancelledAt: isCancelled ? '2026-11-02T14:25:00Z' : undefined,
        whatsappStatus,
        whatsappUpdatedAt: batch.lastUpdated,
        whatsappFailureReason,
        qrVerificationCode: `QR-${certNum}`,
        grade: cand.result,
      });
    });
  });

  return certs;
}

