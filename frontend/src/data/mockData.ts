function buildCandidates(batchIndex: number, count: number): Candidate[] {
  return Array.from({ length: count }, (_, idx) => {
    const firstName = FIRST_NAMES[(batchIndex * 7 + idx) % FIRST_NAMES.length];
    const lastName = LAST_NAMES[(batchIndex * 5 + idx * 3) % LAST_NAMES.length];
    const fullName = `${firstName} ${lastName}`;
    const regNum = `PSM-2026-${String(1000 + batchIndex * 100 + idx + 1)}`;
    const score = 68 + ((batchIndex * 11 + idx * 7) % 29);
    const attendance = 80 + ((batchIndex * 3 + idx * 5) % 19);
    const phoneSuffix = String(100000 + ((batchIndex * 131 + idx * 79) % 899999));
    const aadhaar4 = String(1000 + ((batchIndex * 313 + idx * 97) % 8999));

    return {
      id: `cand-${batchIndex}-${idx + 1}`,
      registrationNumber: regNum,
      fullName,
      email: `${firstName.toLowerCase()}.${lastName.toLowerCase()}${idx + 1}@candidate.in`,
      phone: `+91 9823${phoneSuffix}`,
      aadhaarMasked: `XXXX-XXXX-${aadhaar4}`,
      assessmentScore: score,
      attendancePercent: attendance,
      result: score >= 85 ? 'Distinction' : 'Pass',
    };
  });
}

